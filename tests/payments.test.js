const test = require('node:test');
const assert = require('node:assert');
const crypto = require('node:crypto');
const { DatabaseSync } = require('node:sqlite');

test('Payments: Mock Sandbox flow creates and verifies atomic order state transition', () => {
  const db = new DatabaseSync(':memory:');
  db.exec(`
    CREATE TABLE orders (
      id TEXT PRIMARY KEY,
      order_number TEXT UNIQUE NOT NULL,
      amount_cents INTEGER NOT NULL,
      currency TEXT NOT NULL,
      payment_status TEXT NOT NULL DEFAULT 'pending',
      payment_reference TEXT,
      updated_at TEXT NOT NULL
    );
  `);

  const orderNumber = 'ORD-TEST-999';
  const now = new Date().toISOString();
  db.prepare(`
    INSERT INTO orders (id, order_number, amount_cents, currency, payment_status, updated_at)
    VALUES (?, ?, ?, ?, 'pending', ?)
  `).run('ord_1', orderNumber, 2500000, 'INR', now);

  // Simulate payment completion
  const paymentRef = 'mock_ref_99999';
  db.prepare(`
    UPDATE orders 
    SET payment_status = 'completed', payment_reference = ?, updated_at = ?
    WHERE order_number = ?
  `).run(paymentRef, new Date().toISOString(), orderNumber);

  const updatedOrder = db.prepare('SELECT * FROM orders WHERE order_number = ?').get(orderNumber);
  assert.strictEqual(updatedOrder.payment_status, 'completed');
  assert.strictEqual(updatedOrder.payment_reference, paymentRef);
});

test('Payments: Razorpay cryptographic HMAC-SHA256 signature verification', () => {
  const keySecret = 'sample_secret_key_xyz123';
  const orderId = 'order_9A33X56A44a5AX';
  const paymentId = 'pay_29AoAQID70AA5m';

  // Correct signature generated by gateway
  const expectedSignature = crypto
    .createHmac('sha256', keySecret)
    .update(`${orderId}|${paymentId}`)
    .digest('hex');

  function verifyRazorpaySignature(oId, pId, sig, secret) {
    const generated = crypto
      .createHmac('sha256', secret)
      .update(`${oId}|${pId}`)
      .digest('hex');
    return crypto.timingSafeEqual(Buffer.from(generated, 'hex'), Buffer.from(sig, 'hex'));
  }

  assert.strictEqual(
    verifyRazorpaySignature(orderId, paymentId, expectedSignature, keySecret),
    true,
    'Valid signature must verify successfully'
  );

  const tamperedSignature = crypto
    .createHmac('sha256', 'wrong_secret')
    .update(`${orderId}|${paymentId}`)
    .digest('hex');

  assert.strictEqual(
    verifyRazorpaySignature(orderId, paymentId, tamperedSignature, keySecret),
    false,
    'Tampered signature must be rejected'
  );
});
